/// Semua yang bisa dicari: makanan jadi + bahan makanan.
final List<Dish> kAllDishes = [
  ...kDishes,
  for (final f in kFoods) Dish.fromFood(f),
];

final Map<String, Dish> kDishById = {for (final d in kAllDishes) d.id: d};

String _norm(String s) =>
    s.toLowerCase().replaceAll(RegExp(r'[^a-z0-9 ]'), ' ').trim();

/// Cari makanan: semua kata harus cocok (awalan kata) di nama/alias.
List<Dish> searchDishes(String q, {DishCat? cat, int limit = 60}) {
  final tokens = _norm(q).split(RegExp(r'\s+')).where((t) => t.isNotEmpty);
  final out = <(int, Dish)>[];
  for (final d in kAllDishes) {
    if (cat != null && d.cat != cat) continue;
    final name = _norm(d.name);
    final words = '$name ${_norm(d.aliases)}'.split(RegExp(r'\s+'));
    var ok = true;
    var score = 0;
    for (final t in tokens) {
      if (words.any((w) => w.startsWith(t))) {
        if (name.startsWith(t)) score += 3;
        if (name.split(' ').any((w) => w.startsWith(t))) score += 2;
      } else if (name.contains(t)) {
        score += 1;
      } else {
        ok = false;
        break;
      }
    }
    if (!ok) continue;
    // makanan jadi didahulukan dari bahan mentah
    if (d.cat != DishCat.bahan) score += 1;
    out.add((score, d));
  }
  out.sort((a, b) => b.$1.compareTo(a.$1));
  return [for (final e in out.take(limit)) e.$2];
}
