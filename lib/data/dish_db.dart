enum DishCat {
  berat('Makanan Berat', Icons.dinner_dining, Color(0xFFFFB74D)),
  lauk('Lauk', Icons.set_meal, Color(0xFFEF5350)),
  sayur('Sayur', Icons.grass, Color(0xFF66BB6A)),
  jajanan('Jajanan & Gorengan', Icons.bakery_dining, Color(0xFFFFD54F)),
  buah('Buah', Icons.apple, Color(0xFFFF8A65)),
  minuman('Minuman', Icons.local_cafe, Color(0xFF4FC3F7)),
  bahan('Bahan Makanan', Icons.kitchen, Color(0xFFB39DDB));

  const DishCat(this.label, this.icon, this.color);
  final String label;
  final IconData icon;
  final Color color;
}

class Dish {
  const Dish(
    this.id,
    this.name,
    this.cat,
    this.portion,
    this.kcal,
    this.protein,
    this.carbs,
    this.fat, {
    this.aliases = '',
    this.fried = false,
    this.sweet = false,
  });

  final String id;
  final String name;
  final DishCat cat;

  /// Ukuran 1 porsi, mis. "1 piring (300 g)".
  final String portion;

  /// Nilai gizi per 1 porsi.
  final double kcal, protein, carbs, fat;

  /// Kata kunci pencarian tambahan (dipisah spasi).
  final String aliases;

  /// Digoreng / tinggi minyak.
  final bool fried;

  /// Minuman / makanan tinggi gula tambahan.
  final bool sweet;

  /// Bahan mentah dari [kFoods] → 1 porsi = 1 satuan rumah tangga.
  factory Dish.fromFood(Food f) {
    final k = f.unitGrams / 100;
    return Dish(
      'food:${f.id}',
      f.name,
      DishCat.bahan,
      '${f.unit} (${f.unitGrams.round()} ${f.g})',
      f.kcal * k,
      f.protein * k,
      f.carbs * k,
      f.fat * k,
      aliases: f.cat.label,
    );
  }
}

