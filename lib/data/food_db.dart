final Map<String, MealTemplate> kMealById = {
  for (final t in kMealTemplates) t.id: t,
};

/// URL gambar bahan: foto Commons bila ada, kalau tidak gambar TheMealDB.
String? foodImageUrl(Food f, {bool small = true}) {
  if (f.photo != null) return kDishPhotos[f.photo]?.url;
  if (f.mealDb != null) {
    return 'https://www.themealdb.com/images/ingredients/'
        '${Uri.encodeComponent(f.mealDb!)}${small ? '-Small' : ''}.png';
  }
  return null;
}

/// URL foto menu: foto masakan, atau gambar bahan utama sebagai cadangan.
String? mealImageUrl(MealTemplate t) {
  if (t.photo != null && kDishPhotos[t.photo] != null) {
    return kDishPhotos[t.photo]!.url;
  }
  for (final c in t.components) {
    final f = kFoodById[c.foodId];
    if (f != null && f.cat != FoodCat.lemak) {
      return foodImageUrl(f, small: false);
    }
  }
  return null;
}

/// Apakah menu mengandung bahan yang dipantang.
bool mealExcluded(MealTemplate t, Set<FoodTag> excluded) {
  if (excluded.isEmpty) return false;
  return t.components.any(
    (c) => kFoodById[c.foodId]!.tags.any(excluded.contains),
  );
}
